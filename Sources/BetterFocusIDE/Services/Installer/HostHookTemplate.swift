        ANSWER_WITH_INPUT = ("claude_code", "trae", "trae_cn")


        def answer_value(question, label):
            text = label or ""
            if question.get("multiSelect"):
                parts = [part.strip() for part in text.replace("、", ",").split(",")]
                text = ", ".join(part for part in parts if part)
            return text


        def answered_input(payload, questions, labels):
            tool_input = payload.get("tool_input")
            updated = dict(tool_input) if isinstance(tool_input, dict) else {}
            answers = {}
            for question, label in zip(questions, labels):
                key = question.get("question") or question.get("header") or ""
                value = answer_value(question, label)
                if key and value:
                    answers[key] = value
            if not updated.get("questions"):
                updated["questions"] = questions
            updated["answers"] = answers
            return updated


        def answer_reason(questions, labels):
            lines = []
            for question, label in zip(questions, labels):
                lines.append("  - %s: %s" % (question.get("header") or "Question", label))
            return ("The person answered on the BetterFocusIDE island. "
                    "Use these answers and continue." + chr(10) + chr(10).join(lines))


        def emit_answered(hook_event, payload, questions, labels):
            if PROVIDER in ANSWER_WITH_INPUT:
                json.dump({"hookSpecificOutput": {
                    "hookEventName": hook_event or "PreToolUse",
                    "permissionDecision": "allow",
                    "updatedInput": answered_input(payload, questions, labels),
                }}, sys.stdout)
                sys.stdout.write(chr(10))
                sys.stdout.flush()
                return
            if EVENT_STYLE == "copilot":
                # 文档的决策字段是顶层 permissionDecision + modifiedArgs。
                json.dump({
                    "permissionDecision": "allow",
                    "modifiedArgs": answered_input(payload, questions, labels),
                }, sys.stdout)
                sys.stdout.write(chr(10))
                sys.stdout.flush()
                return
            reason = answer_reason(questions, labels)
            if PROVIDER == "kimi":
                # 文档示例没有 hookEventName，多写字段会让严格解析直接丢弃整段。
                json.dump({"hookSpecificOutput": {
                    "permissionDecision": "deny",
                    "permissionDecisionReason": reason,
                }}, sys.stdout)
                sys.stdout.write(chr(10))
                sys.stdout.flush()
                return
            emit("deny", reason, hook_event)


        def release_question(hook_event, reason):
            # 交回宿主自己的提问框。Claude / Trae 写出没有 answers 的 allow
            # 等于跳过提问；Copilot 的 allow 会直接放行工具。这两类什么都不写。
            if PROVIDER in ANSWER_WITH_INPUT or EVENT_STYLE == "copilot":
                return
            emit(host_decides(hook_event), reason, hook_event)


        def host_decides(hook_event):
            # PermissionRequest 是我们和宿主抢「谁先弹」的那条通道：平台正等我们
            # 的答复，`ask` = 把它自己的弹窗放出来。PreToolUse 平台不等答复，
            # 只认 allow/deny，那里用 allow 退场（等于不干预）。
            return "ask" if hook_event == "PermissionRequest" else "allow"


        def run_question(session_id, payload, questions, hook_event):
            # 同一个提问会从两条通道各来一次（PermissionRequest 与 PreToolUse），
            # 载荷里的 tool_use_id 不保证两边都有，所以按**问题内容**去重：
            # 先到的那条占位并开卡，后到的安静退出，绝不让同一道题问两遍。
            signature = "q-" + "_".join(q["question"][:40] for q in questions)[:120]
            if not claim(session_id, payload, "question", signature):
                return
            request_id = safe_id(payload.get("tool_use_id")
                                 or payload.get("toolUseId")
                                 or payload.get("call_id")
                                 or payload.get("request_id")
                                 or ("q" + str(int(time.time()))))
            msg = base_event("question_requested", session_id, payload)
            msg["request_id"] = request_id
            msg["payload"] = {"questions": questions, "request_id": request_id,
                              # 哪条通道送来的（PermissionRequest / PreToolUse / …）。
                              # 「岛先出现」能不能成立全看这个：PermissionRequest 上
                              # 平台正等着我们的答复，宿主还没画自己的面板。
                              "channel": hook_event}
            if not send(msg):
                release_question(hook_event, "BetterFocusIDE is not running; ask in the host dialog.")
                return
            # 岛可能早就弹过卡（Notification 预取那条通道），用户也已经答完：
            # 直接把答案回灌，绝不再问第二遍，也不必再等一个超时。
            # 只处理单题——多题卡片是逐步写的，提前取会吃掉一半。
            if len(questions) == 1:
                found, label, index = read_answer(session_id, request_id,
                                                  questions[0]["id"], 0)
                if found and index >= 0:
                    emit_answered(hook_event, payload, questions, [label])
                    return
                if found and index == -4:
                    release_question(hook_event, "The person will answer in the host dialog.")
                    return
            since = time.time()
            deadline = since + QUESTION_TIMEOUT
            while time.time() < deadline:
                labels, answered, timed_out = [], 0, False
                for q in questions:
                    found, label, index = read_answer(session_id, request_id, q["id"], since)
                    if found and index == -4:
                        # 让位：宿主自带提问面板且正在前台。静默退出（不打印任何
                        # 决策）是本方言的「无决策」——宿主自己的对话框接手。
                        return
                    if found and index == -1:
                        timed_out = True
                    elif found:
                        answered += 1
                    labels.append(label if found and index >= 0 else "")
                if timed_out:
                    break
                if answered == len(questions) and questions:
                    emit_answered(hook_event, payload, questions, labels)
                    return
                time.sleep(1)
            timeout_msg = base_event("question_timeout", session_id, payload)
            timeout_msg["payload"] = {"question_id": questions[0]["id"] if questions else "q1",
                                      "request_id": request_id}
            send(timeout_msg)
            # 没人回答：交回宿主自己的对话框。Claude / Trae 不能回没有
            # answers 的 allow，那会跳过提问框；deny 则把工具判失败。
            release_question(hook_event,
                             "The person left the island question unanswered; ask in the host dialog.")


        def run_permission(session_id, payload):
            # Notice only: print NOTHING on stdout so the host keeps its own
            # permission dialog. Observer of last resort — the island-side
            # NoticeController debounces a duplicate banner.
            if not claim(session_id, payload, "permission"):
                return
            tool_name = payload.get("tool_name") or ""
            tool_input = payload.get("tool_input") if isinstance(payload.get("tool_input"), dict) else {}
            request_id = safe_id(payload.get("tool_use_id")
                                 or payload.get("toolUseId")
                                 or payload.get("request_id")
                                 or (tool_name + "-" + str(int(time.time() * 1000))))
            detail = ""
            for key in ("command", "file_path", "path", "url", "query", "pattern"):
                value = tool_input.get(key)
                if isinstance(value, str) and value:
                    detail = value
                    break
            if not detail and tool_input:
                detail = json.dumps(tool_input, ensure_ascii=False)[:400]
            if not detail:
                detail = str(payload.get("message") or "")[:400]
            msg = base_event("permission_notice", session_id, payload)
            msg["payload"] = {"request_id": request_id, "tool_name": tool_name,
                              "tool_input": tool_input,
                              "resources": [detail] if detail else [],
                              "flavor": "permission"}
            send(msg)


        # ------------------------------------------------------------------
        # 诊断探针：仅当 /tmp/bf-probe 标记存在时启用，把收到的事件原始
        # 结构 dump 到 /tmp 下可读文件，用来在真机上定位 WorkBuddy 转录里
        # 提问块的真实形状（字段名 / 嵌套层级）。探针是旁路观测，不影响
        # 正常分发决策；验证完删掉标记文件即可静默。
        # ------------------------------------------------------------------
        PROBE = os.path.exists("/tmp/bf-probe")
        PROBE_EVENTS = "/tmp/bf-probe-events.log"
        PROBE_TRANS = "/tmp/bf-probe-transcript.log"

        def _probe(text):
            if not PROBE:
                return
            try:
                with open(PROBE_EVENTS, "a") as fh:
                    fh.write(time.strftime("%H:%M:%S", time.localtime()) + " " + text + chr(10))
            except Exception:
                pass

        def _probe_payload(payload, event):
            # 只挑「提问/权限」相关的字段 dump，避免把整个 transcript 或大
            # 文本打进日志；键值超过 400 字符就截断。
            if not PROBE:
                return
            keys = ("hook_event_name", "hookEventName", "tool_name", "toolName",
                    "notification_type", "message", "transcript_path",
                    "transcriptPath", "permission_mode", "permissionMode",
                    "tool_use_id", "toolUseId", "request_id", "session_id")
            seen = {}
            for key in keys:
                if key in payload:
                    value = payload[key]
                    if isinstance(value, str):
                        value = value[:400]
                    seen[key] = value
            _probe("event=%s payload=%s" % (event, json.dumps(seen, ensure_ascii=False)))
            # 有 tool_input / input 的话，看它里面有没有 questions（题面在哪一层）
            for k in ("tool_input", "input"):
                v = payload.get(k)
                if isinstance(v, dict):
                    _probe("  %s.keys=%s" % (k, list(v.keys())))
                    if v.get("questions"):
                        _probe("  %s.questions=%s" % (k, json.dumps(v["questions"], ensure_ascii=False)[:800]))
            # 转录尾部：把含 "question" 的原始行原样 dump，供定位真实形状
            tp = payload.get("transcript_path") or payload.get("transcriptPath") or ""
            if isinstance(tp, str) and tp and os.path.exists(tp):
                _probe("  transcript_path=%s exists" % tp)
                try:
                    size = os.path.getsize(tp)
                    with open(tp, "rb") as fh:
                        if size > 1024 * 1024:
                            fh.seek(size - 1024 * 1024)
                            fh.readline()
                        raw = fh.read().decode("utf-8", "ignore")
                    hits = 0
                    with open(PROBE_TRANS, "a") as out:
                        for line in raw.splitlines():
                            if "question" in line.lower():
                                out.write(line + chr(10))
                                hits += 1
                                if hits >= 40:
                                    break
                    _probe("  transcript question-lines=%d" % hits)
                except Exception as exc:
                    _probe("  transcript-read-failed:%s" % exc)


        def read_payload():
            # Codex 有两条入口，不能混：
            # - notify：JSON 在 argv[1]。stdin 往往不关闭，读下去会把终端卡死。
            # - hooks.json：没有 argv，JSON 在 stdin，和 Claude 系一样。
            if EVENT_STYLE == "codex" and len(sys.argv) > 1:
                try:
                    return json.loads(sys.argv[1])
                except Exception:
                    return {}
            try:
                return json.load(sys.stdin)
            except Exception:
                return {}


        def normalise_copilot(payload):
            # PascalCase 配置的载荷已经是 snake_case。这里兜住 camelCase
            # 配置（以及 ask_user / update_todo 这两个运行时名字），让后面的
            # 分发只认 Claude 系字段。
            aliases = {
                "sessionStart": "SessionStart",
                "sessionEnd": "SessionEnd",
                "userPromptSubmitted": "UserPromptSubmit",
                "preToolUse": "PreToolUse",
                "postToolUse": "PostToolUse",
                "agentStop": "Stop",
                "permissionRequest": "PermissionRequest",
                "notification": "Notification",
                "errorOccurred": "ErrorOccurred",
                "postToolUseFailure": "PostToolUseFailure",
                "subagentStop": "SubagentStop",
                "preCompact": "PreCompact",
                "postCompact": "PostCompact",
                "stopFailure": "StopFailure",
            }
            event = payload.get("hook_event_name") or payload.get("hookEventName") or ""
            mapped = aliases.get(event, event)
            if mapped:
                payload["hook_event_name"] = mapped
            if not payload.get("tool_name") and payload.get("toolName"):
                name = str(payload.get("toolName"))
                tools = {"ask_user": "AskUserQuestion", "update_todo": "TodoWrite"}
                payload["tool_name"] = tools.get(name, name)
            if not isinstance(payload.get("tool_input"), dict):
                args = payload.get("toolArgs")
                if args is None:
                    args = payload.get("toolInput")
                if isinstance(args, dict):
                    payload["tool_input"] = args
            tool_input = payload.get("tool_input")
            if isinstance(tool_input, dict):
                has_question = tool_input.get("questions") or tool_input.get("question")
                text = tool_input.get("prompt") or tool_input.get("message")
                if not has_question and isinstance(text, str) and text:
                    tool_input["question"] = text
            if payload.get("transcriptPath") and not payload.get("transcript_path"):
                payload["transcript_path"] = payload["transcriptPath"]
            return payload


        def emit_status(event_name, session_id, payload, title, body):
            # 失败 / 子任务 / 待审阅 / 压缩。只发横幅，stdout 保持空，
            # 绝不给宿主回决策。
            if not alerts_enabled("turn") or not os.path.exists(SOCKET_PATH):
                return
            msg = base_event(event_name, session_id, payload)
            msg["payload"] = {
                "title": " ".join(str(title or "").split())[:80],
                "body": " ".join(str(body or "").split())[:180],
                "transcript_path": transcript_path_of(payload),
            }
            send(msg)


        def status_detail(payload):
            for key in ("error", "reason", "message", "last_assistant_message",
                        "stderr", "failure_reason"):
                text = first_text(payload, (key,), 180)
                if text:
                    return text
            tool = str(payload.get("tool_name") or payload.get("toolName") or "")
            response = payload.get("tool_response") or payload.get("toolResponse")
            if isinstance(response, dict):
                for key in ("message", "error", "stderr"):
                    value = response.get(key)
                    if isinstance(value, str) and value.strip():
                        text = " ".join(value.split())
                        return (tool + "：" + text)[:180] if tool else text[:180]
            return tool[:180]


        def failure_title(event, payload):
            kind = str(payload.get("notification_type") or payload.get("error_type") or "")
            if kind.startswith("quota_"):
                return "额度不足"
            if kind == "auth_storage_failure":
                return "登录状态失效"
            if event == "PermissionDenied":
                return "自动模式拒绝了这次操作"
            if event in ("ErrorOccurred", "errorOccurred"):
                return "执行出错"
            return "这一轮没有完成"


        def main():
            payload = read_payload()
            if not isinstance(payload, dict):
                payload = {}
            if EVENT_STYLE == "copilot":
                payload = normalise_copilot(payload)
            event = payload.get("hook_event_name") or payload.get("hookEventName") or ""
            session_id = session_id_of(payload)
            mode = str(payload.get("permission_mode") or payload.get("permissionMode") or "")
            _probe_payload(payload, event)

            if EVENT_STYLE == "codex" and payload.get("type") == "agent-turn-complete":
                # notify 入口只有这一种事件。hooks.json 的载荷带 hook_event_name，
                # 落到下面的 Claude 方言分发（提问、权限静默、Stop / SessionEnd）。
                if alerts_enabled("turn"):
                    emit_turn_finished(session_id, codex_turn_payload(payload))
                return

            if EVENT_STYLE == "cursor":
                # Observe-only on purpose. Registering a Cursor permission hook
                # would force us to return allow (bypassing the user's approval)
                # or deny (blocking the tool); an invalid response blocks too.
                if not event:
                    event = infer_cursor_event(payload)
                if event == "beforeSubmitPrompt":
                    cache_user_prompt(session_id, payload)
                    # 文档要求用 continue 放行。省略时部分版本会把提交拦掉。
                    sys.stdout.write('{"continue": true}' + chr(10))
                    sys.stdout.flush()
                    return
                if event == "stop":
                    if alerts_enabled("turn"):
                        emit_turn_finished(session_id, payload)
                elif event == "sessionEnd":
                    emit_session_ended(session_id, payload)
                elif event == "errorOccurred":
                    emit_status("failure_notice", session_id, payload,
                                failure_title(event, payload), status_detail(payload))
                elif event == "subagentStop":
                    detail = status_detail(payload) or "子任务已结束"
                    emit_status("subagent_finished", session_id, payload,
                                "子任务完成", detail)
                elif event == "preCompact":
                    emit_status("compact_notice", session_id, payload,
                                "即将压缩上下文", "")
                cursor_ok()
                return

            # Claude/WorkBuddy dialect. Silence on stdout means "no decision":
            # the host keeps its own dialogs and the agent loop is never blocked.
            if event == "Stop":
                if alerts_enabled("turn"):
                    emit_turn_finished(session_id, payload)
                return
            if event == "SessionEnd":
                emit_session_ended(session_id, payload)
                return

            # 用户输入缓存：Stop 事件的载荷里没有 prompt，完成通知的标题/正文
            # 靠 UserPromptSubmit 在这里把最新输入写盘，Stop 时读回直报。
            # 发后即忘，不打印任何东西、不等答。
            if event == "UserPromptSubmit":
                cache_user_prompt(session_id, payload)
                return

            # 状态横幅：回合失败、自动拒绝、执行出错、子任务、压缩。只通知，不回决策。
            # 工具调用失败不通知。旧安装里 PostToolUseFailure 可能还挂着，进来就退出。
            if event in ("PostToolUseFailure", "postToolUseFailure"):
                return
            if event in ("StopFailure", "PermissionDenied", "ErrorOccurred"):
                emit_status("failure_notice", session_id, payload,
                            failure_title(event, payload), status_detail(payload))
                return
            if event == "SubagentStop":
                detail = status_detail(payload) or "子任务已结束"
                emit_status("subagent_finished", session_id, payload, "子任务完成", detail)
                return
            if event in ("PostCompact", "PreCompact"):
                title = "上下文已压缩" if event == "PostCompact" else "即将压缩上下文"
                emit_status("compact_notice", session_id, payload, title, "")
                return
            if event == "Elicitation":
                found = pending_question(payload) if alerts_enabled("question") else None
                if found and os.path.exists(SOCKET_PATH):
                    if not emit_question_notice(session_id, payload, found[1]):
                        preview_question(session_id, payload, found[1], found[0])
                else:
                    emit_status("review_notice", session_id, payload, "需要你的输入",
                                str(payload.get("message") or ""))
                return

            # 待办进度：只在 PostToolUse 上转发。todo 家族走整表/单条；
            # Copilot CLI 的 TodoWrite 实际是会话库 `sql`。发后即忘，
            # 不打印任何东西、不等答。
            if event == "PostToolUse":
                tool = str(payload.get("tool_name") or payload.get("toolName") or "")
                if os.path.exists(SOCKET_PATH):
                    if tool in TODO_OVERWRITE_TOOLS or tool in TODO_UPSERT_TOOLS:
                        handle_todo_event(session_id, payload, tool)
                    elif tool == "sql":
                        emit_copilot_sql_todos(session_id, payload)
                return

            # 提问先于一切权限判定分发。
            #
            # 两条通道的语义完全不同（实测结论，参考 dynamic-Island-python-validate）：
            # - PermissionRequest：平台**等**我们的答复。等的这段时间里，宿主还没
            #   画出它自己的问卷——这就是「岛先出现」的窗口：岛开卡、作答、回
            #   deny + reason，答案直接灌给工具，宿主那份面板根本没机会出现。
            # - PreToolUse：fire-and-forget，平台不等答复。只用来兜住不发
            #   PermissionRequest 的旧入口，谁先到谁占位（见 run_question 去重）。
            #
            # 提问也不是权限：以前把它挂在下面的权限分支里，等于拿「权限提醒开关」
            # 和「自动执行档」给它当门——auto 档在那一层直接 return，岛连事件都收
            # 不到，宿主顺手弹出自己的问卷，看起来就是「IDE 先弹」。
            tool_name = str(payload.get("tool_name") or "")
            # 宿主自己弹提问面板的那一刻只发一条 Notification：没有 tool_name、
            # 没有 tool_input，只有一句 "needs your permission to use
            # AskUserQuestion"。这是**唯一**一条早于用户作答的信号（PreToolUse
            # 要等面板答完才来），题面只能从转录里捞。捞到就先出卡。
            if event == "Notification" and not looks_like_question(payload, tool_name):
                kind = str(payload.get("notification_type") or "")
                message = str(payload.get("message") or "")
                # Trae 的任务完成不走 Stop 的通知语义，官方类型是 idle_prompt。
                # 漏掉它，回合结束岛上什么都不会出。
                if kind == "idle_prompt":
                    if alerts_enabled("turn"):
                        emit_turn_finished(session_id, payload)
                    return
                if kind in ("document_review", "browser_interaction"):
                    title = "文档待审阅" if kind == "document_review" else "浏览器在等你"
                    emit_status("review_notice", session_id, payload, title, message)
                    return
                if kind == "auth_storage_failure" or kind.startswith("quota_"):
                    emit_status("failure_notice", session_id, payload,
                                failure_title(event, payload), message)
                    return
                if kind in ("agent_needs_input", "elicitation_url_dialog"):
                    emit_status("review_notice", session_id, payload, "需要你的输入", message)
                    return
                if kind == "elicitation_dialog":
                    found = None
                    if alerts_enabled("question") and os.path.exists(SOCKET_PATH):
                        found = pending_question(payload)
                    if found:
                        if not emit_question_notice(session_id, payload, found[1]):
                            preview_question(session_id, payload, found[1], found[0])
                    else:
                        emit_status("review_notice", session_id, payload,
                                    "需要你的输入", message)
                    return
                hint = message.lower()
                # Trae 的提问通知类型是 ask_user_question。没有题面，只能从转录里捞。
                question_notice = kind == "ask_user_question" or (
                    (not kind or kind == "permission_prompt")
                    and any(name in hint for name in ("askuserquestion",
                                                      "ask_user_question",
                                                      "ask_followup_question")))
                if (question_notice and alerts_enabled("question")
                        and os.path.exists(SOCKET_PATH)):
                    found = pending_question(payload)
                    if found:
                        if not emit_question_notice(session_id, payload, found[1]):
                            preview_question(session_id, payload, found[1], found[0])
                        return
                    if kind == "ask_user_question":
                        return
            if looks_like_question(payload, tool_name):
                # WorkBuddy：这条要等用户在 IDE 里答完才到。通知已经在
                # Notification 那一次发出。再走 run_question 会再弹一张提问卡。
                # 这里不回决策，宿主沿用刚提交的答案。
                if PROVIDER == "workbuddy":
                    questions = normalise(payload.get("tool_input") or {})
                    if questions:
                        emit_question_notice(session_id, payload, questions)
                    return
                if not alerts_enabled("question") or not os.path.exists(SOCKET_PATH):
                    release_question(event or "PreToolUse",
                                     "BetterFocusIDE question cards are off; ask in the host dialog.")
                    return
                questions = normalise(payload.get("tool_input") or {})
                if questions:
                    run_question(session_id, payload, questions, event or "PreToolUse")
                else:
                    release_question(event or "PreToolUse", "Nothing to ask; continue.")
                return

            # 权限提醒：Notification 是文档化的观测入口，PermissionRequest 是真正
            # 会等人的那条。两边都只递一条提醒、不替人拍板（岛侧 NoticeController
            # 负责去掉重复横幅）。
            if event in ("Notification", "PermissionRequest"):
                kind = str(payload.get("notification_type") or "")
                if event == "Notification" and kind and kind != "permission_prompt":
                    return
                if mode in AUTO_MODES or not alerts_enabled("permission") or not os.path.exists(SOCKET_PATH):
                    return
                run_permission(session_id, payload)
                return

            # PreToolUse 上的其余工具：静默退出。平台不等这个事件的答复，
            # 在这里提醒只会「闪一下什么都没发生」。


        if __name__ == "__main__":
            try:
                main()
            except Exception:
                # Copilot 的 preToolUse 崩溃等于拒绝这次工具调用。提问被
                # 误拒比「退回原生对话框」更糟，所以这里吞掉异常、以 0 退出。
                if EVENT_STYLE != "copilot":
                    raise
        """
}

/// 两个 hook 安装器共用的文件 / JSON 工具。
///
/// 不变量：写宿主配置时只增删带 `betterfocus-notify.sh` 标记的条目，其余字段
/// （尤其是 WorkBuddy settings.json 里的账号 / 插件配置）原样保留；原子写回后
/// 恢复原文件权限，避免把 0600 的设置文件放宽成 0644。
enum HookInstallerSupport {
    static let scriptName = "betterfocus-notify.sh"
    static let helperName = "betterfocus-hook.py"

    /// 读取宿主配置；缺失或畸形时返回空字典。
    static func loadJSON(_ path: String) -> [String: Any] {
        guard let data = try? Data(contentsOf: URL(fileURLWithPath: path)),
              let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any]
        else { return [:] }
        return json
    }

    /// 原子写回 JSON，并保留原文件的 POSIX 权限位。
    static func writeJSON(_ object: [String: Any], to path: String) throws {
        let url = URL(fileURLWithPath: path)
        let dir = url.deletingLastPathComponent()
        try FileManager.default.createDirectory(atPath: dir.path, withIntermediateDirectories: true)
        var mode: mode_t?
        if let attrs = try? FileManager.default.attributesOfItem(atPath: path),
           let number = attrs[.posixPermissions] as? NSNumber {
            mode = mode_t(number.uint16Value)
        }
        let data = try JSONSerialization.data(withJSONObject: object,
                                              options: [.prettyPrinted, .sortedKeys])
        try data.write(to: url, options: .atomic)
        if let mode { chmod(path, mode) }
    }

    /// 内容未变则不重写，保持 mtime 稳定（宿主会监听配置文件变化）。
    static func ensureFile(path: String, content: String, executable: Bool) throws {
        let dir = (path as NSString).deletingLastPathComponent
        try FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true)
        if let existing = try? String(contentsOfFile: path, encoding: .utf8),
           existing == content {
            if executable { chmod(path, 0o755) }
            return
        }
        try content.write(toFile: path, atomically: true, encoding: .utf8)
        if executable { chmod(path, 0o755) }
    }

    /// 通过 command 路径识别我们自己的条目（不依赖宿主是否容忍自定义字段）。
    static func isOurCommand(_ value: Any?) -> Bool {
        guard let command = value as? String else { return false }
        return command.contains(scriptName)
    }

    /// 分组里是否含我们的 command（WorkBuddy 的 matcher 分组结构）。
    static func isOurGroup(_ group: [String: Any]) -> Bool {
        if (group["_betterfocus_marker"] as? String) == InstallerPaths.marker { return true }
        if let entries = group["hooks"] as? [[String: Any]] {
            return entries.contains { isOurCommand($0["command"]) }
        }
        return isOurCommand(group["command"])
    }

    /// 极小 shell 启动器；python3 缺失时静默退出 0，绝不阻塞宿主。
    /// 不输出任何 JSON：对 WorkBuddy 意味着「无决策、按原流程」，对 Cursor
    /// 的观测型 hook 也只是没有附加输出。
    ///
    /// `"$@"` 必须原样转交：Codex 的 notify 把事件 JSON 当成**命令行参数**传进来，
    /// 少了这一步 codex 侧永远收不到 payload（stdin 是空的）。
    static func scriptContent() -> String {
        """
        #!/bin/bash
        # BetterFocusIDE <-> host hook launcher. Forwards lifecycle events to the
        # Dynamic Island. All JSON work lives in betterfocus-hook.py beside it.

        SELF_DIR="$(cd "$(dirname "$0")" && pwd)"
        PYTHON=$(command -v python3 || echo /usr/bin/python3)

        if [ ! -x "$PYTHON" ]; then
          exit 0
        fi

        # `-S` 跳过 site 初始化：这脚本只用标准库，而 site 会把机器上所有
        # site-packages 的 .pth 走一遍。实测同一台机器 `python3 -c pass`
        # 273ms、`python3 -S -c pass` 33ms——省下的 240ms 全都在「岛上出卡」
        # 的关键路径上，宿主自己的面板早在模型吐出 tool_use 时就画好了。
        exec "$PYTHON" -S "$SELF_DIR/betterfocus-hook.py" "$@"
        """
    }

    /// 生成 Python 正文：替换命名空间路径、超时、provider、事件方言与宿主兜底身份。
    static func helperContent(provider: String, style: String,
                              hostBundle: String, hostName: String, hostPath: String) -> String {
        HostHookTemplate.body
            .replacingOccurrences(of: "__SOCKET_PATH__", with: InstallerPaths.socketPath)
            .replacingOccurrences(of: "__ANSWER_DIR__", with: InstallerPaths.answerDir)
            .replacingOccurrences(of: "__SETTINGS_PATH__", with: InstallerPaths.settingsPath)
            .replacingOccurrences(of: "__QUESTION_TIMEOUT__", with: "\(InstallerPaths.questionTimeoutSeconds)")
            .replacingOccurrences(of: "__PERMISSION_TIMEOUT__", with: "\(InstallerPaths.permissionTimeoutSeconds)")
            .replacingOccurrences(of: "__PROVIDER__", with: provider)
            .replacingOccurrences(of: "__EVENT_STYLE__", with: style)
            .replacingOccurrences(of: "__HOST_BUNDLE__", with: hostBundle)
            .replacingOccurrences(of: "__HOST_NAME__", with: hostName)
            .replacingOccurrences(of: "__HOST_PATH__", with: hostPath)
    }
}
