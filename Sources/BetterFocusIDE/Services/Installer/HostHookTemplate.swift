/// Cursor / WorkBuddy 共用的内嵌 Python hook 正文。
///
/// 两个宿主的 hook 都是「stdin 收 JSON、stdout 回 JSON」的 command hook，但事件
/// 方言不同：
/// - Cursor：`~/.cursor/hooks.json`，camelCase（`stop` / `sessionEnd`），权限类 hook
///   返回非法 JSON 会阻塞工具调用，因此只注册观测型事件，恒回 `{}`。
/// - WorkBuddy：`~/.workbuddy/settings.json` 的 `hooks`，PascalCase
///   （`Stop` / `SessionEnd` / `PreToolUse` / `PermissionRequest`），输出
///   `hookSpecificOutput.permissionDecision`，与既有 Qoder hook 同构。
///
/// 应答走同一条通道：灵动岛写 `answers/<session>...json`，脚本轮询取走。
/// 占位符在安装时替换（路径 / 超时 / provider / 事件方言 / 宿主兜底身份）。
enum HostHookTemplate {
    static let body = """
        #!/usr/bin/env python3
        # BetterFocusIDE <-> host hook body (Cursor / WorkBuddy).
        # Generated by BetterFocusIDE; reinstalling overwrites this file.
        #
        # EVENT_STYLE switches between the two hook dialects:
        #   cursor : observe-only, always answer an empty JSON object
        #   claude : WorkBuddy, may answer questions / permissions via decisions
        import json
        import os
        import socket
        import subprocess
        import sys
        import time

        PROVIDER = os.environ.get("BETTERFOCUS_PROVIDER") or "__PROVIDER__"
        EVENT_STYLE = os.environ.get("BETTERFOCUS_EVENT_STYLE") or "__EVENT_STYLE__"
        SOCKET_PATH = os.environ.get("BETTERFOCUS_SOCKET_PATH") or "__SOCKET_PATH__"
        ANSWER_DIR = os.environ.get("BETTERFOCUS_ANSWER_DIR") or "__ANSWER_DIR__"
        SETTINGS_PATH = os.environ.get("BETTERFOCUS_SETTINGS_PATH") or "__SETTINGS_PATH__"
        QUESTION_TIMEOUT = int(os.environ.get("BETTERFOCUS_QUESTION_TIMEOUT", "__QUESTION_TIMEOUT__"))
        PERMISSION_TIMEOUT = int(os.environ.get("BETTERFOCUS_PERMISSION_TIMEOUT", "__PERMISSION_TIMEOUT__"))

        # Fallback host identity when the parent-process walk finds nothing.
        HOST_BUNDLE = "__HOST_BUNDLE__"
        HOST_NAME = "__HOST_NAME__"
        HOST_PATH = "__HOST_PATH__"

        AUTO_MODES = ("accept_edits", "acceptEdits", "auto",
                      "bypass_permissions", "bypassPermissions", "yolo", "dont_ask")

        # Shell / interpreter hops between the hook and the host .app.
        SKIP_COMM = frozenset(("sh", "bash", "zsh", "fish", "dash", "ksh", "csh",
                               "tcsh", "nu", "xonsh", "env", "python", "python3"))


        def alerts_enabled(kind):
            key = {"question": "question_enabled", "permission": "permission_enabled",
                   "turn": "turn_notify_enabled"}.get(kind)
            if not key:
                return True
            try:
                with open(SETTINGS_PATH) as f:
                    parsed = json.load(f)
                values = (parsed or {}).get("values", {})
                if key not in values:
                    return True
                return values[key] is not False
            except Exception:
                return True


        def send(message):
            # Fire-and-forget: the answer comes back through the answer files.
            try:
                s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
                s.settimeout(1.0)
                s.connect(SOCKET_PATH)
                s.sendall((json.dumps(message) + chr(10)).encode("utf-8"))
                s.close()
                return True
            except Exception:
                return False


        def emit(decision, reason, event):
            # Claude/WorkBuddy style decision envelope.
            json.dump({"hookSpecificOutput": {
                "hookEventName": event,
                "permissionDecision": decision,
                "permissionDecisionReason": reason,
            }}, sys.stdout)
            sys.stdout.write(chr(10))
            sys.stdout.flush()


        def cursor_ok():
            # Cursor expects a JSON object back. An empty object is valid and
            # carries no followup_message, so the agent loop really stops.
            sys.stdout.write("{}" + chr(10))
            sys.stdout.flush()


        def safe_id(value):
            return "".join(c if c.isalnum() or c in "-_." else "_" for c in str(value or ""))[:80]


        def answer_names(session_id, request_id, question_id):
            names = []
            if request_id:
                names.append("%s_%s_%s.json" % (session_id, request_id, question_id))
            names.append("%s_%s.json" % (session_id, question_id))
            return names


        def read_answer(session_id, request_id, question_id, since):
            for name in answer_names(session_id, request_id, question_id):
                path = os.path.join(ANSWER_DIR, name)
                try:
                    if os.path.getmtime(path) < since - 1:
                        continue
                    with open(path) as f:
                        data = json.load(f)
                except Exception:
                    continue
                if data.get("request_id") and request_id and data["request_id"] != request_id:
                    continue
                try:
                    os.remove(path)
                except OSError:
                    pass
                index = data.get("answer_index", -1)
                if not isinstance(index, int):
                    index = -1
                return (True, data.get("answer_label") or "", index)
            return (False, "", -1)


        def normalise(tool_input):
            raw = tool_input.get("questions") if isinstance(tool_input, dict) else None
            if not isinstance(raw, list) or not raw:
                raw = [tool_input] if isinstance(tool_input, dict) else []
            questions = []
            for i, q in enumerate(raw):
                if not isinstance(q, dict):
                    continue
                options = []
                for o in (q.get("options") or []):
                    if isinstance(o, str):
                        options.append({"label": o, "description": ""})
                    elif isinstance(o, dict):
                        options.append({"label": o.get("label") or "",
                                        "description": o.get("description") or ""})
                multi = q.get("multiSelect")
                if multi is None:
                    multi = q.get("multi_select")
                questions.append({
                    "id": q.get("id") or ("q" + str(i + 1)),
                    "header": q.get("header") or "Question",
                    "question": q.get("question") or "",
                    "multiSelect": multi is True,
                    "options": options,
                })
            return questions


        def _app_path(comm):
            if not comm or "/" not in comm:
                return ""
            marker = ".app/Contents/MacOS/"
            idx = comm.find(marker)
            if idx == -1:
                return ""
            return comm[:idx + len(".app")]


        def _bundle_identity(app_path):
            info = os.path.join(app_path, "Contents", "Info.plist")
            try:
                import plistlib
                with open(info, "rb") as f:
                    pl = plistlib.load(f)
                return (pl.get("CFBundleIdentifier", ""), pl.get("CFBundleName", ""))
            except Exception:
                return ("", "")


        def host_app():
            # Walk up to the outermost .app so clicking a notice jumps back to
            # the right window (an IDE-embedded CLI must report the IDE, not sh).
            pid = os.getpid()
            for _hop in range(16):
                try:
                    ppid_raw = subprocess.run(["ps", "-o", "ppid=", "-p", str(pid)],
                                              capture_output=True, timeout=2).stdout.decode().strip()
                except Exception:
                    break
                if not ppid_raw or not ppid_raw.isdigit():
                    break
                pid = int(ppid_raw)
                if pid <= 1:
                    break
                try:
                    comm = subprocess.run(["ps", "-o", "comm=", "-p", str(pid)],
                                          capture_output=True, timeout=2).stdout.decode().strip()
                except Exception:
                    break
                if not comm:
                    break
                if os.path.basename(comm) in SKIP_COMM:
                    continue
                app_path = _app_path(comm)
                if app_path:
                    bundle, name = _bundle_identity(app_path)
                    return {"bundle": bundle, "name": name, "path": app_path}
            bundle = os.environ.get("__CFBundleIdentifier") or ""
            if bundle:
                return {"bundle": bundle, "name": "", "path": ""}
            return {"bundle": "", "name": "", "path": ""}


        _HOST_CACHE = None


        def current_host():
            global _HOST_CACHE
            if _HOST_CACHE is None:
                found = host_app()
                if found["bundle"] or found["name"] or found["path"]:
                    _HOST_CACHE = found
                else:
                    _HOST_CACHE = {"bundle": HOST_BUNDLE, "name": HOST_NAME, "path": HOST_PATH}
            return _HOST_CACHE


        def project_cwd(payload):
            for key in ("cwd", "project_dir"):
                value = payload.get(key)
                if isinstance(value, str) and value:
                    return value
            roots = payload.get("workspace_roots")
            if isinstance(roots, list) and roots and isinstance(roots[0], str) and roots[0]:
                return roots[0]
            for key in ("CURSOR_PROJECT_DIR", "CODEBUDDY_PROJECT_DIR", "CLAUDE_PROJECT_DIR"):
                value = os.environ.get(key)
                if value:
                    return value
            return os.getcwd()


        def session_id_of(payload):
            for key in ("session_id", "sessionId", "conversation_id", "generation_id"):
                value = payload.get(key)
                if value:
                    return str(value)
            return "unknown"


        def transcript_path_of(payload):
            value = payload.get("transcript_path") or os.environ.get("CURSOR_TRANSCRIPT_PATH") or ""
            return value if isinstance(value, str) else ""


        def base_event(event, session_id, payload):
            return {"provider": PROVIDER, "product": PROVIDER,
                    "event": event, "session_id": session_id,
                    "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                    "host": current_host(), "cwd": project_cwd(payload)}


        def emit_turn_finished(session_id, payload):
            msg = base_event("turn_finished", session_id, payload)
            msg["payload"] = {"transcript_path": transcript_path_of(payload)}
            send(msg)


        def emit_session_ended(session_id, payload):
            msg = base_event("session_ended", session_id, payload)
            msg["payload"] = {}
            send(msg)


        def run_question(session_id, payload, questions):
            request_id = safe_id(payload.get("request_id") or ("q" + str(int(time.time()))))
            msg = base_event("question_requested", session_id, payload)
            msg["request_id"] = request_id
            msg["payload"] = {"questions": questions, "request_id": request_id}
            if not send(msg):
                emit("allow", "BetterFocusIDE is not running; ask in the host dialog.", "PreToolUse")
                return
            since = time.time()
            deadline = since + QUESTION_TIMEOUT
            while time.time() < deadline:
                lines, answered, timed_out = [], 0, False
                for q in questions:
                    found, label, index = read_answer(session_id, request_id, q["id"], since)
                    if found and index == -1:
                        timed_out = True
                    elif found:
                        answered += 1
                    lines.append("  - %s: %s" % (q["header"], label))
                if timed_out:
                    break
                if answered == len(questions) and questions:
                    reason = ("The person answered on the BetterFocusIDE island. "
                              "Use these answers and continue." + chr(10) + chr(10).join(lines))
                    emit("deny", reason, "PreToolUse")
                    return
                time.sleep(1)
            timeout_msg = base_event("question_timeout", session_id, payload)
            timeout_msg["payload"] = {"question_id": questions[0]["id"] if questions else "q1",
                                      "request_id": request_id}
            send(timeout_msg)
            emit("deny", "The person left the island question unanswered. Continue without it.",
                 "PreToolUse")


        def run_permission(session_id, payload):
            # Notice only: the host still owns the permission decision.
            tool_name = payload.get("tool_name") or ""
            tool_input = payload.get("tool_input") if isinstance(payload.get("tool_input"), dict) else {}
            request_id = safe_id(payload.get("tool_use_id")
                                 or payload.get("toolUseId")
                                 or payload.get("request_id")
                                 or (tool_name + "-" + str(int(time.time() * 1000))))
            detail = ""
            for key in ("command", "file_path", "path", "url", "query", "pattern"):
                value = tool_input.get(key)
                if isinstance(value, str) and value:
                    detail = value
                    break
            if not detail and tool_input:
                detail = json.dumps(tool_input, ensure_ascii=False)[:400]
            msg = base_event("permission_notice", session_id, payload)
            msg["payload"] = {"request_id": request_id, "tool_name": tool_name,
                              "tool_input": tool_input,
                              "resources": [detail] if detail else [],
                              "flavor": "permission"}
            send(msg)
            emit("ask", "BetterFocusIDE only notifies about permissions; decide in the host dialog.",
                 "PermissionRequest")


        def main():
            try:
                payload = json.load(sys.stdin)
            except Exception:
                payload = {}
            if not isinstance(payload, dict):
                payload = {}
            event = payload.get("hook_event_name") or payload.get("hookEventName") or ""
            session_id = session_id_of(payload)
            mode = str(payload.get("permission_mode") or payload.get("permissionMode") or "")

            if EVENT_STYLE == "cursor":
                # Observe-only on purpose. Registering a Cursor permission hook
                # would force us to return allow (bypassing the user's approval)
                # or deny (blocking the tool); an invalid response blocks too.
                if event == "stop":
                    if alerts_enabled("turn"):
                        emit_turn_finished(session_id, payload)
                elif event == "sessionEnd":
                    emit_session_ended(session_id, payload)
                cursor_ok()
                return

            # Claude/WorkBuddy dialect. Silence on stdout means "no decision".
            if event == "Stop":
                if alerts_enabled("turn"):
                    emit_turn_finished(session_id, payload)
                return
            if event == "SessionEnd":
                emit_session_ended(session_id, payload)
                return
            if event == "PermissionRequest":
                if mode in AUTO_MODES or not alerts_enabled("permission") or not os.path.exists(SOCKET_PATH):
                    emit("ask", "BetterFocusIDE permission notices are off; decide in the host dialog.",
                         "PermissionRequest")
                    return
                run_permission(session_id, payload)
                return
            if event == "PreToolUse":
                tool_name = str(payload.get("tool_name") or "")
                if "AskUserQuestion" in tool_name:
                    if not alerts_enabled("question") or not os.path.exists(SOCKET_PATH):
                        emit("allow", "BetterFocusIDE question cards are off; ask in the host dialog.",
                             "PreToolUse")
                        return
                    questions = normalise(payload.get("tool_input") or {})
                    if questions:
                        run_question(session_id, payload, questions)
                    else:
                        emit("allow", "Nothing to ask; continue.", "PreToolUse")
                return


        if __name__ == "__main__":
            main()
        """
}

/// 两个 hook 安装器共用的文件 / JSON 工具。
///
/// 不变量：写宿主配置时只增删带 `betterfocus-notify.sh` 标记的条目，其余字段
/// （尤其是 WorkBuddy settings.json 里的账号 / 插件配置）原样保留；原子写回后
/// 恢复原文件权限，避免把 0600 的设置文件放宽成 0644。
enum HookInstallerSupport {
    static let scriptName = "betterfocus-notify.sh"
    static let helperName = "betterfocus-hook.py"

    /// 读取宿主配置；缺失或畸形时返回空字典。
    static func loadJSON(_ path: String) -> [String: Any] {
        guard let data = try? Data(contentsOf: URL(fileURLWithPath: path)),
              let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any]
        else { return [:] }
        return json
    }

    /// 原子写回 JSON，并保留原文件的 POSIX 权限位。
    static func writeJSON(_ object: [String: Any], to path: String) throws {
        let url = URL(fileURLWithPath: path)
        let dir = url.deletingLastPathComponent()
        try FileManager.default.createDirectory(atPath: dir.path, withIntermediateDirectories: true)
        var mode: mode_t?
        if let attrs = try? FileManager.default.attributesOfItem(atPath: path),
           let number = attrs[.posixPermissions] as? NSNumber {
            mode = mode_t(number.uint16Value)
        }
        let data = try JSONSerialization.data(withJSONObject: object,
                                              options: [.prettyPrinted, .sortedKeys])
        try data.write(to: url, options: .atomic)
        if let mode { chmod(path, mode) }
    }

    /// 内容未变则不重写，保持 mtime 稳定（宿主会监听配置文件变化）。
    static func ensureFile(path: String, content: String, executable: Bool) throws {
        let dir = (path as NSString).deletingLastPathComponent
        try FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true)
        if let existing = try? String(contentsOfFile: path, encoding: .utf8),
           existing == content {
            if executable { chmod(path, 0o755) }
            return
        }
        try content.write(toFile: path, atomically: true, encoding: .utf8)
        if executable { chmod(path, 0o755) }
    }

    /// 通过 command 路径识别我们自己的条目（不依赖宿主是否容忍自定义字段）。
    static func isOurCommand(_ value: Any?) -> Bool {
        guard let command = value as? String else { return false }
        return command.contains(scriptName)
    }

    /// 分组里是否含我们的 command（WorkBuddy 的 matcher 分组结构）。
    static func isOurGroup(_ group: [String: Any]) -> Bool {
        if (group["_betterfocus_marker"] as? String) == InstallerPaths.marker { return true }
        if let entries = group["hooks"] as? [[String: Any]] {
            return entries.contains { isOurCommand($0["command"]) }
        }
        return isOurCommand(group["command"])
    }

    /// 极小 shell 启动器；python3 缺失时静默退出 0，绝不阻塞宿主。
    /// 不输出任何 JSON：对 WorkBuddy 意味着「无决策、按原流程」，对 Cursor
    /// 的观测型 hook 也只是没有附加输出。
    static func scriptContent() -> String {
        """
        #!/bin/bash
        # BetterFocusIDE <-> host hook launcher. Forwards lifecycle events to the
        # Dynamic Island. All JSON work lives in betterfocus-hook.py beside it.

        SELF_DIR="$(cd "$(dirname "$0")" && pwd)"
        PYTHON=$(command -v python3 || echo /usr/bin/python3)

        if [ ! -x "$PYTHON" ]; then
          exit 0
        fi

        exec "$PYTHON" "$SELF_DIR/betterfocus-hook.py"
        """
    }

    /// 生成 Python 正文：替换命名空间路径、超时、provider、事件方言与宿主兜底身份。
    static func helperContent(provider: String, style: String,
                              hostBundle: String, hostName: String, hostPath: String) -> String {
        HostHookTemplate.body
            .replacingOccurrences(of: "__SOCKET_PATH__", with: InstallerPaths.socketPath)
            .replacingOccurrences(of: "__ANSWER_DIR__", with: InstallerPaths.answerDir)
            .replacingOccurrences(of: "__SETTINGS_PATH__", with: InstallerPaths.settingsPath)
            .replacingOccurrences(of: "__QUESTION_TIMEOUT__", with: "\(InstallerPaths.questionTimeoutSeconds)")
            .replacingOccurrences(of: "__PERMISSION_TIMEOUT__", with: "\(InstallerPaths.permissionTimeoutSeconds)")
            .replacingOccurrences(of: "__PROVIDER__", with: provider)
            .replacingOccurrences(of: "__EVENT_STYLE__", with: style)
            .replacingOccurrences(of: "__HOST_BUNDLE__", with: hostBundle)
            .replacingOccurrences(of: "__HOST_NAME__", with: hostName)
            .replacingOccurrences(of: "__HOST_PATH__", with: hostPath)
    }
}
