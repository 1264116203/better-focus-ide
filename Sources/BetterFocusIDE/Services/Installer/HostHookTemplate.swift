/// 两个 hook 安装器共用的文件 / JSON 工具。
///
/// 不变量：写宿主配置时只增删带 `betterfocus-notify.sh` 标记的条目，其余字段
/// （尤其是 WorkBuddy settings.json 里的账号 / 插件配置）原样保留；原子写回后
/// 恢复原文件权限，避免把 0600 的设置文件放宽成 0644。
enum HookInstallerSupport {
    static let scriptName = "betterfocus-notify.sh"
    static let helperName = "betterfocus-hook.py"

    /// 读取宿主配置；缺失或畸形时返回空字典。
    static func loadJSON(_ path: String) -> [String: Any] {
        guard let data = try? Data(contentsOf: URL(fileURLWithPath: path)),
              let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any]
        else { return [:] }
        return json
    }

    /// 原子写回 JSON，并保留原文件的 POSIX 权限位。
    static func writeJSON(_ object: [String: Any], to path: String) throws {
        let url = URL(fileURLWithPath: path)
        let dir = url.deletingLastPathComponent()
        try FileManager.default.createDirectory(atPath: dir.path, withIntermediateDirectories: true)
        var mode: mode_t?
        if let attrs = try? FileManager.default.attributesOfItem(atPath: path),
           let number = attrs[.posixPermissions] as? NSNumber {
            mode = mode_t(number.uint16Value)
        }
        let data = try JSONSerialization.data(withJSONObject: object,
                                              options: [.prettyPrinted, .sortedKeys])
        try data.write(to: url, options: .atomic)
        if let mode { chmod(path, mode) }
    }

    /// 内容未变则不重写，保持 mtime 稳定（宿主会监听配置文件变化）。
    static func ensureFile(path: String, content: String, executable: Bool) throws {
        let dir = (path as NSString).deletingLastPathComponent
        try FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true)
        if let existing = try? String(contentsOfFile: path, encoding: .utf8),
           existing == content {
            if executable { chmod(path, 0o755) }
            return
        }
        try content.write(toFile: path, atomically: true, encoding: .utf8)
        if executable { chmod(path, 0o755) }
    }

    /// 通过 command 路径识别我们自己的条目（不依赖宿主是否容忍自定义字段）。
    static func isOurCommand(_ value: Any?) -> Bool {
        guard let command = value as? String else { return false }
        return command.contains(scriptName)
    }

    /// 分组里是否含我们的 command（WorkBuddy 的 matcher 分组结构）。
    static func isOurGroup(_ group: [String: Any]) -> Bool {
        if (group["_betterfocus_marker"] as? String) == InstallerPaths.marker { return true }
        if let entries = group["hooks"] as? [[String: Any]] {
            return entries.contains { isOurCommand($0["command"]) }
        }
        return isOurCommand(group["command"])
    }

    /// 极小 shell 启动器；python3 缺失时静默退出 0，绝不阻塞宿主。
    /// 不输出任何 JSON：对 WorkBuddy 意味着「无决策、按原流程」，对 Cursor
    /// 的观测型 hook 也只是没有附加输出。
    ///
    /// `"$@"` 必须原样转交：Codex 的 notify 把事件 JSON 当成**命令行参数**传进来，
    /// 少了这一步 codex 侧永远收不到 payload（stdin 是空的）。
    static func scriptContent() -> String {
        """
        #!/bin/bash
        # BetterFocusIDE <-> host hook launcher. Forwards lifecycle events to the
        # Dynamic Island. All JSON work lives in betterfocus-hook.py beside it.

        SELF_DIR="$(cd "$(dirname "$0")" && pwd)"
        PYTHON=$(command -v python3 || echo /usr/bin/python3)

        if [ ! -x "$PYTHON" ]; then
          exit 0
        fi

        # `-S` 跳过 site 初始化：这脚本只用标准库，而 site 会把机器上所有
        # site-packages 的 .pth 走一遍。实测同一台机器 `python3 -c pass`
        # 273ms、`python3 -S -c pass` 33ms——省下的 240ms 全都在「岛上出卡」
        # 的关键路径上，宿主自己的面板早在模型吐出 tool_use 时就画好了。
        exec "$PYTHON" -S "$SELF_DIR/betterfocus-hook.py" "$@"
        """
    }

    /// 生成 Python 正文：替换命名空间路径、超时、provider、事件方言与宿主兜底身份。
    static func helperContent(provider: String, style: String,
                              hostBundle: String, hostName: String, hostPath: String) -> String {
        HostHookTemplate.body
            .replacingOccurrences(of: "__SOCKET_PATH__", with: InstallerPaths.socketPath)
            .replacingOccurrences(of: "__ANSWER_DIR__", with: InstallerPaths.answerDir)
            .replacingOccurrences(of: "__SETTINGS_PATH__", with: InstallerPaths.settingsPath)
            .replacingOccurrences(of: "__QUESTION_TIMEOUT__", with: "\(InstallerPaths.questionTimeoutSeconds)")
            .replacingOccurrences(of: "__PERMISSION_TIMEOUT__", with: "\(InstallerPaths.permissionTimeoutSeconds)")
            .replacingOccurrences(of: "__PROVIDER__", with: provider)
            .replacingOccurrences(of: "__EVENT_STYLE__", with: style)
            .replacingOccurrences(of: "__HOST_BUNDLE__", with: hostBundle)
            .replacingOccurrences(of: "__HOST_NAME__", with: hostName)
            .replacingOccurrences(of: "__HOST_PATH__", with: hostPath)
    }
