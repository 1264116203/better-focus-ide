import Foundation

/// 内嵌的 Python hook 正文，一份代码覆盖各宿主方言。
///
/// 所有宿主都是「收 JSON、按需回 JSON」的 command hook，差别只在方言：
/// - `cursor`：`~/.cursor/hooks.json`，camelCase。权限类 hook 返回非法 JSON
///   会阻塞工具调用，因此只注册观测型事件。`stop` / `sessionEnd` 回 `{}`，
///   `beforeSubmitPrompt` 回 `{"continue": true}`。
/// - `claude`：Claude Code / WorkBuddy / Trae / Kimi 这一族，PascalCase。
///   Claude Code 与 Trae 的提问按官方格式回 `allow` + `updatedInput.answers`；
///   Kimi 回 `deny` + `permissionDecisionReason`。WorkBuddy 的提问只发通知、
///   不接管，PreToolUse 保持静默。权限只观测，
///   stdout 保持静默，让宿主原生对话框继续负责审批。
/// - `copilot`：GitHub Copilot CLI。配置用 PascalCase，决策是顶层字段。
///   提问回 `allow` + `modifiedArgs`；其余 `allow` / `ask` 必须静默，
///   写出去等于替用户放行工具。`preToolUse` 失败是 fail-closed。
/// - `codex`：ChatGPT（原 Codex）有两条入口。`notify` 把 JSON 放在 argv[1]，
///   只有 `agent-turn-complete`；`~/.codex/hooks.json` 则和 Claude 一样走 stdin，
///   事件名是 PascalCase。有 argv 时绝不能读 stdin（notify 不关 stdin，读了会卡死终端）。
///
/// 应答走同一条通道：灵动岛写 `answers/<session>...json`，脚本轮询取走。
/// 占位符在安装时替换（路径 / 超时 / provider / 事件方言 / 宿主兜底身份）。
enum HostHookTemplate {
    static let body = """
        #!/usr/bin/env python3
        # BetterFocusIDE <-> host hook body (Cursor / WorkBuddy).
        # Generated by BetterFocusIDE; reinstalling overwrites this file.
        #
        # EVENT_STYLE switches between the hook dialects:
        #   cursor  : observe-only, always answer an empty JSON object
        #   claude  : Claude Code family, answer questions via decisions
        #   copilot : GitHub Copilot CLI, top-level decision, never allow
        #   codex   : notify uses argv; hooks.json uses stdin. Never read stdin
        #             when argv already carries the payload.
        import json
        import os
        import socket
        import sys
        import time
        # 故意不在这里 import subprocess：它会把 threading / enum / functools
        # 全拖进来，实测多花 ~100ms，而这条进程就在「岛什么时候出卡」的关键
        # 路径上。只有需要走进程祖先链的宿主（烘焙身份为空的 CLI）才在
        # host_app() 里现用现导入。

        PROVIDER = os.environ.get("BETTERFOCUS_PROVIDER") or "__PROVIDER__"
        EVENT_STYLE = os.environ.get("BETTERFOCUS_EVENT_STYLE") or "__EVENT_STYLE__"
        SOCKET_PATH = os.environ.get("BETTERFOCUS_SOCKET_PATH") or "__SOCKET_PATH__"
        ANSWER_DIR = os.environ.get("BETTERFOCUS_ANSWER_DIR") or "__ANSWER_DIR__"
        SETTINGS_PATH = os.environ.get("BETTERFOCUS_SETTINGS_PATH") or "__SETTINGS_PATH__"
        QUESTION_TIMEOUT = int(os.environ.get("BETTERFOCUS_QUESTION_TIMEOUT", "__QUESTION_TIMEOUT__"))
        PERMISSION_TIMEOUT = int(os.environ.get("BETTERFOCUS_PERMISSION_TIMEOUT", "__PERMISSION_TIMEOUT__"))

        # Fallback host identity when the parent-process walk finds nothing.
        HOST_BUNDLE = "__HOST_BUNDLE__"
        HOST_NAME = "__HOST_NAME__"
        HOST_PATH = "__HOST_PATH__"

        AUTO_MODES = ("accept_edits", "acceptEdits", "auto",
                      "bypass_permissions", "bypassPermissions", "yolo", "dont_ask")

        # Shell / interpreter hops between the hook and the host .app.
        SKIP_COMM = frozenset(("sh", "bash", "zsh", "fish", "dash", "ksh", "csh",
                               "tcsh", "nu", "xonsh", "env", "python", "python3"))


        def alerts_enabled(kind):
            # 设置文件里 `values` 的键是驼峰（Settings 的 @Published 名），
            # 旧版 Python 实现用的是下划线键。两种都认，驼峰优先。
            keys = {"question": ("questionEnabled", "question_enabled"),
                    "permission": ("permissionEnabled", "permission_enabled"),
                    "turn": ("turnNotifyEnabled", "turn_notify_enabled")}.get(kind)
            if not keys:
                return True
            try:
                with open(SETTINGS_PATH) as f:
                    parsed = json.load(f)
                values = (parsed or {}).get("values", {})
                for key in keys:
                    if key in values:
                        return values[key] is not False
                return True
            except Exception:
                return True


        def send(message):
            # Fire-and-forget: the answer comes back through the answer files.
            try:
                s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
                s.settimeout(1.0)
                s.connect(SOCKET_PATH)
                s.sendall((json.dumps(message) + chr(10)).encode("utf-8"))
                s.close()
                return True
            except Exception:
                return False


        def emit(decision, reason, event):
            # Copilot 不认 hookSpecificOutput。顶层 deny 才是「拦住工具、把
            # 答案回灌给模型」。allow 会直接放行，ask 会弹出它自己的审批框
            # 而不是提问框——这两种都等于替用户做了决定，所以什么都不写，
            # 让原生对话框接手。退出码必须是 0：preToolUse 上非 0 是拒绝。
            if EVENT_STYLE == "copilot":
                if decision in ("ask", "allow"):
                    return
                if event == "PermissionRequest":
                    body = {"behavior": "deny", "message": reason}
                else:
                    body = {"permissionDecision": "deny",
                            "permissionDecisionReason": reason}
                json.dump(body, sys.stdout)
                sys.stdout.write(chr(10))
                sys.stdout.flush()
                return
            # Claude/WorkBuddy style decision envelope.
            json.dump({"hookSpecificOutput": {
                "hookEventName": event,
                "permissionDecision": decision,
                "permissionDecisionReason": reason,
            }}, sys.stdout)
            sys.stdout.write(chr(10))
            sys.stdout.flush()


        def cursor_ok():
            # Cursor expects a JSON object back. An empty object is valid and
            # carries no followup_message, so the agent loop really stops.
            sys.stdout.write("{}" + chr(10))
            sys.stdout.flush()


        def infer_cursor_event(payload):
            # 文档里的单事件示例省略了通用字段 hook_event_name。按各事件
            # 示例里独有的字段把事件名补回来，避免完成横幅被静默丢掉。
            if payload.get("status") in ("completed", "aborted", "error") and "loop_count" in payload:
                return "stop"
            reasons = ("completed", "aborted", "error", "window_close", "user_close")
            if payload.get("reason") in reasons and "duration_ms" in payload:
                return "sessionEnd"
            if isinstance(payload.get("prompt"), str) and "attachments" in payload:
                return "beforeSubmitPrompt"
            return ""


        def safe_id(value):
            return "".join(c if c.isalnum() or c in "-_." else "_" for c in str(value or ""))[:80]


        def answer_names(session_id, request_id, question_id):
            names = []
            if request_id:
                names.append("%s_%s_%s.json" % (session_id, request_id, question_id))
            names.append("%s_%s.json" % (session_id, question_id))
            return names


        def read_answer(session_id, request_id, question_id, since):
            for name in answer_names(session_id, request_id, question_id):
                path = os.path.join(ANSWER_DIR, name)
                try:
                    if os.path.getmtime(path) < since - 1:
                        continue
                    with open(path) as f:
                        data = json.load(f)
                except Exception:
                    continue
                if data.get("request_id") and request_id and data["request_id"] != request_id:
                    continue
                try:
                    os.remove(path)
                except OSError:
                    pass
                index = data.get("answer_index", -1)
                if not isinstance(index, int):
                    index = -1
                # DEFER_INDEX：岛侧判定「宿主就在前台、它自己会画提问面板」，
                # 于是放弃接管。此时什么都不用回——stdout 静默就是「无决策」，
                # 宿主按原生流程把问题问出来，用户只答一次。
                if data.get("defer") is True or index == -4:
                    return (True, "", -4)
                return (True, data.get("answer_label") or "", index)
            return (False, "", -1)


        def claim(session_id, payload, kind, signature=""):
            # 同一个事件可能被两套配置同时注册：Trae 会一并读取 ~/.claude 的
            # hooks，于是同一个 AskUserQuestion 会被两条脚本各处理一次，弹出
            # 两张一模一样的卡片。用一个短命占位文件做互斥——先到先得，
            # 后到的安静退出，把决定权留给先到的那条。
            key = safe_id("%s_%s_%s" % (session_id, kind,
                                        signature
                                        or payload.get("tool_use_id")
                                        or payload.get("toolUseId")
                                        or payload.get("request_id")
                                        or payload.get("tool_name")))
            path = os.path.join(ANSWER_DIR, ".claim_" + key)
            try:
                os.makedirs(ANSWER_DIR, exist_ok=True)
                if os.path.exists(path) and time.time() - os.path.getmtime(path) < 20:
                    return False
                with open(path, "w") as f:
                    f.write(str(time.time()))
                return True
            except Exception:
                return True


        def looks_like_question(payload, tool_name):
            # 工具名各家写法不一（AskUserQuestion / ask_user_question / question /
            # ask_followup_question），有的宿主只给 tool_input.questions 不给名字
            # （Qoder 的 PermissionRequest 里 tool_name 是权限种类 "permission"）。
            folded = str(tool_name or "").strip().lower()
            if folded in ("askuserquestion", "ask_user", "ask_user_question",
                          "ask_followup_question", "question"):
                return True
            if "askuserquestion" in folded:
                return True
            tool_input = payload.get("tool_input")
            return isinstance(tool_input, dict) and bool(tool_input.get("questions"))


        def _collect_tool_blocks(node, uses, results):
            # 转录的写法跨版本不一。实测 WorkBuddy 是：
            #   type="function_call", name="AskUserQuestion",
            #   arguments=JSON 字符串（解析后 {"questions": [...]}），
            #   callId 关联结果块 type="function_call_result"。
            # 旧宿主（Claude/Cursor/Trae）是 type=tool_use/tool_call，
            #   name/toolName + input/tool_input(dict)。按形状都认。
            if isinstance(node, dict):
                name = str(node.get("name") or node.get("tool_name")
                           or node.get("toolName") or "")
                # 结果块：function_call_result 用 callId 关联，其他用 tool_use_id
                tid = node.get("callId") or node.get("tool_use_id") \
                    or node.get("toolUseId") or node.get("call_id")
                ntype = str(node.get("type") or "")
                if isinstance(tid, str) and tid and (
                        "result" in ntype.lower() or not node.get("arguments")
                        and not node.get("input") and not node.get("tool_input")):
                    results.add(tid)
                # 题面：优先 WorkBuddy 的 arguments 字符串，其次 input/tool_input dict
                body = None
                args = node.get("arguments")
                if isinstance(args, str) and args:
                    try:
                        parsed = json.loads(args)
                        if isinstance(parsed, dict) and parsed.get("questions"):
                            body = parsed
                    except Exception:
                        pass
                if body is None:
                    body = node.get("input") if isinstance(node.get("input"), dict) else None
                if body is None and isinstance(node.get("tool_input"), dict):
                    body = node.get("tool_input")
                if "question" in name.lower() and body and body.get("questions"):
                    uses.append((node.get("callId") or node.get("id")
                                 or node.get("tool_use_id")
                                 or node.get("call_id") or "", body))
                for value in node.values():
                    _collect_tool_blocks(value, uses, results)
            elif isinstance(node, list):
                for value in node:
                    _collect_tool_blocks(value, uses, results)


        def _prefetch_note(text):
            # 预取只在“太晚”和“没捞到”上出问题，而这两种情况在真机上只能靠
            # 事后翻日志判断；留一行薄的诊断，不写就别查了。
            try:
                path = os.path.join(os.path.dirname(ANSWER_DIR), "prefetch.log")
                if os.path.exists(path) and os.path.getsize(path) > 64 * 1024:
                    os.remove(path)
                with open(path, "a") as fh:
                    fh.write(time.strftime("%H:%M:%S", time.localtime())
                             + " " + text + chr(10))
            except Exception:
                pass


        def _scan_transcript(path):
            # 返回 (tool_use_id, 题面) 或 None，并把扫描规模写进诊断。
            try:
                size = os.path.getsize(path)
                with open(path, "rb") as fh:
                    if size > 1024 * 1024:
                        fh.seek(size - 1024 * 1024)
                        fh.readline()
                    raw = fh.read().decode("utf-8", "ignore")
            except Exception as exc:
                return (None, "read-failed:%s" % exc)
            uses, results, bad = [], set(), 0
            lines = raw.splitlines()
            for line in lines:
                line = line.strip()
                if not line:
                    continue
                try:
                    _collect_tool_blocks(json.loads(line), uses, results)
                except Exception:
                    bad += 1
            note = "size=%d lines=%d uses=%d results=%d bad=%d" % (
                size, len(lines), len(uses), len(results), bad)
            for ident, body in reversed(uses):
                if ident and ident in results:
                    continue
                questions = normalise(body)
                if questions:
                    return ((ident, questions), note)
            return (None, note)


        def pending_question(payload):
            # 宿主的提问面板一出现就发一条 Notification（permission_prompt），
            # 但那条载荷里**没有题面**——只有一句
            # "needs your permission to use AskUserQuestion"。题面在转录里：
            # 模型发出的 tool_use 通常已经落盘。读尾部、找最后一条还没有结果的
            # 提问调用，岛就能在面板刚出现时把同一道题画出来——这是唯一一条
            # 早于“用户作答”的通道。落盘可能比通知晚几十毫秒，所以短轮询几次。
            path = payload.get("transcript_path") or payload.get("transcriptPath") or ""
            if not isinstance(path, str) or not path:
                return None
            note = ""
            for attempt in range(8):
                found, note = _scan_transcript(path)
                if found:
                    _prefetch_note("hit try=%d %s" % (attempt, note))
                    return found
                time.sleep(0.15)
            _prefetch_note("miss path=%s %s" % (path, note))
            return None


        def preview_question(session_id, payload, questions, tool_use_id):
            # 只出卡、不作答：Notification 这条通道没有可回灌的决策，所以发完
            # 事件就退出。用户在岛上先答，等宿主真正执行工具（PreToolUse）时，
            # run_question 会发现答案已经在了，直接 deny 回灌，不会再问一遍。
            # 占位互斥：与 run_question 用同一份 signature，谁先到谁开卡，
            # 后到的（PreToolUse / PermissionRequest）静默退出，绝不弹第二遍。
            signature = "q-" + "_".join(q["question"][:40] for q in questions)[:120]
            if not claim(session_id, payload, "question", signature):
                return
            request_id = safe_id(tool_use_id or ("q" + str(int(time.time()))))
            msg = base_event("question_requested", session_id, payload)
            msg["request_id"] = request_id
            msg["payload"] = {"questions": questions, "request_id": request_id,
                              "channel": "Notification"}
            send(msg)


        def emit_question_notice(session_id, payload, questions):
            # WorkBuddy 的提问不接管。宿主面板和这条通知同时出现，点通知跳回
            # WorkBuddy 去答。PreToolUse 要等面板答完才来，再开一张提问卡就是
            # 第二次弹出——同一份占位让后到的事件直接离开，不再发卡片。
            if PROVIDER != "workbuddy":
                return False
            if not alerts_enabled("question") or not os.path.exists(SOCKET_PATH):
                return True
            signature = "q-" + "_".join(q.get("question", "")[:40] for q in questions)[:120]
            if not claim(session_id, payload, "question", signature):
                return True
            first = questions[0] if questions else {}
            title = " ".join(str(first.get("header") or "需要你的回答").split())[:80]
            body = " ".join(str(first.get("question") or "").split())
            if len(questions) > 1:
                extra = "（共 %d 题）" % len(questions)
                body = ((body + " " + extra) if body else extra)[:180]
            if not body:
                body = "请在 WorkBuddy 里回答"
            msg = base_event("question_notice", session_id, payload)
            msg["payload"] = {
                "title": title,
                "body": body[:180],
                "transcript_path": transcript_path_of(payload),
            }
            send(msg)
            return True


        def normalise(tool_input):
            raw = tool_input.get("questions") if isinstance(tool_input, dict) else None
            if not isinstance(raw, list) or not raw:
                raw = [tool_input] if isinstance(tool_input, dict) else []
            questions = []
            for i, q in enumerate(raw):
                if not isinstance(q, dict):
                    continue
                options = []
                for o in (q.get("options") or []):
                    if isinstance(o, str):
                        options.append({"label": o, "description": ""})
                    elif isinstance(o, dict):
                        options.append({"label": o.get("label") or "",
                                        "description": o.get("description") or ""})
                multi = q.get("multiSelect")
                if multi is None:
                    multi = q.get("multi_select")
                questions.append({
                    "id": q.get("id") or ("q" + str(i + 1)),
                    "header": q.get("header") or "Question",
                    "question": q.get("question") or "",
                    "multiSelect": multi is True,
                    "options": options,
                })
            return questions


        def _app_path(comm):
            if not comm or "/" not in comm:
                return ""
            marker = ".app/Contents/MacOS/"
            idx = comm.find(marker)
            if idx == -1:
                return ""
            return comm[:idx + len(".app")]


        def _bundle_identity(app_path):
            info = os.path.join(app_path, "Contents", "Info.plist")
            try:
                import plistlib
                with open(info, "rb") as f:
                    pl = plistlib.load(f)
                return (pl.get("CFBundleIdentifier", ""), pl.get("CFBundleName", ""))
            except Exception:
                return ("", "")


        def host_app():
            # Walk up to the outermost .app so clicking a notice jumps back to
            # the right window (an IDE-embedded CLI must report the IDE, not sh).
            import subprocess  # 见文件头的说明：只为这一步付启动成本。
            pid = os.getpid()
            for _hop in range(16):
                try:
                    ppid_raw = subprocess.run(["ps", "-o", "ppid=", "-p", str(pid)],
                                              capture_output=True, timeout=2).stdout.decode().strip()
                except Exception:
                    break
                if not ppid_raw or not ppid_raw.isdigit():
                    break
                pid = int(ppid_raw)
                if pid <= 1:
                    break
                try:
                    comm = subprocess.run(["ps", "-o", "comm=", "-p", str(pid)],
                                          capture_output=True, timeout=2).stdout.decode().strip()
                except Exception:
                    break
                if not comm:
                    break
                if os.path.basename(comm) in SKIP_COMM:
                    continue
                app_path = _app_path(comm)
                if app_path:
                    bundle, name = _bundle_identity(app_path)
                    return {"bundle": bundle, "name": name, "path": app_path}
            bundle = os.environ.get("__CFBundleIdentifier") or ""
            if bundle:
                return {"bundle": bundle, "name": "", "path": ""}
            return {"bundle": "", "name": "", "path": ""}


        _HOST_CACHE = None


        def current_host():
            # 装的时候烘焙了宿主身份（GUI 宿主：WorkBuddy / Qoder / Trae / Cursor）
            # 就直接用，不爬进程祖先链——爬链每一步都要拉一个 `ps`，实测 ~55ms，
            # 而它正好挡在 `send()` 前面，也就是挡在岛上出卡前面。这些宿主本来就是
            # 由它自己的 .app 拉起来的，祖先链最终找到的也是同一个身份。
            # 烘焙身份为空的是 CLI 宿主（Claude Code / Codex / Kimi），那些才真的
            # 需要爬链找出「外面是哪个终端」。
            global _HOST_CACHE
            if _HOST_CACHE is None:
                if HOST_BUNDLE or HOST_NAME:
                    _HOST_CACHE = {"bundle": HOST_BUNDLE, "name": HOST_NAME, "path": HOST_PATH}
                else:
                    found = host_app()
                    if found["bundle"] or found["name"] or found["path"]:
                        _HOST_CACHE = found
                    else:
                        _HOST_CACHE = {"bundle": HOST_BUNDLE, "name": HOST_NAME, "path": HOST_PATH}
            return _HOST_CACHE


        def project_cwd(payload):
            for key in ("cwd", "project_dir"):
                value = payload.get(key)
                if isinstance(value, str) and value:
                    return value
            roots = payload.get("workspace_roots")
            if isinstance(roots, list) and roots and isinstance(roots[0], str) and roots[0]:
                return roots[0]
            for key in ("CURSOR_PROJECT_DIR", "CODEBUDDY_PROJECT_DIR", "CLAUDE_PROJECT_DIR"):
                value = os.environ.get(key)
                if value:
                    return value
            return os.getcwd()


        def session_id_of(payload):
            for key in ("session_id", "sessionId", "conversation_id", "generation_id",
                        "thread-id", "thread_id", "turn-id"):
                value = payload.get(key)
                if value:
                    return str(value)
            return "unknown"


        def transcript_path_of(payload):
            value = (payload.get("transcript_path") or payload.get("transcriptPath")
                     or os.environ.get("CURSOR_TRANSCRIPT_PATH") or "")
            return value if isinstance(value, str) else ""


        def base_event(event, session_id, payload):
            return {"provider": PROVIDER, "product": PROVIDER,
                    "event": event, "session_id": session_id,
                    "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                    "host": current_host(), "cwd": project_cwd(payload)}


        # 宿主偶尔会把会话主题直接放进 hook payload（而不是只给 transcript 路径）。
        # 各家键名不一，按候选表取第一个非空值；取不到就留空，由应用侧
        # 退回到读 transcript —— 这里绝不臆造标题。
        TITLE_KEYS = ("session_title", "sessionTitle", "conversation_title",
                      "conversationTitle", "title")
        PROMPT_KEYS = ("prompt", "user_prompt", "userPrompt",
                       "last_prompt", "lastPrompt", "message")


        def first_text(payload, keys, limit=200):
            for key in keys:
                value = payload.get(key)
                if isinstance(value, str):
                    text = " ".join(value.split())
                    if text:
                        return text[:limit]
            return ""


