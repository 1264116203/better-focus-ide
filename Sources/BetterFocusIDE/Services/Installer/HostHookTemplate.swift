        def todo_input(payload):
            \"\"\"todo 工具的入参：优先 tool_input，其次 input（部分宿主键名不同）。\"\"\"
            value = payload.get("tool_input") or payload.get("input")
            return value if isinstance(value, dict) else {}


        def emit_todo_overwrite(session_id, payload):
            \"\"\"整表覆盖（TodoWrite / todowrite / SetTodoList）。

            Claude Code V2 血统的 TodoWrite 带 `merge` 参数：merge=True 时只传
            变化的那几条。岛侧按整表覆盖处理、没有合并能力，所以 merge=True
            必须在这里拆成单条 `todo_item_updated` 交给岛侧 UPSERT，否则会把
            没出现的那几条全抹掉。
            \"\"\"
            args = todo_input(payload)
            raw = args.get("todos") or args.get("tasks")
            if not isinstance(raw, list):
                # 少数宿主把结果放在 tool_response 里（写入后的回读）。
                response = payload.get("tool_response")
                if isinstance(response, dict):
                    raw = response.get("todos") or response.get("tasks")
            if not isinstance(raw, list):
                return
            todos = normalise_todos(raw)
            if not todos:
                return
            if args.get("merge") is True:
                for item in todos:
                    msg = base_event("todo_item_updated", session_id, payload)
                    msg["payload"] = {"todo": item}
                    send(msg)
                return
            msg = base_event("todo_updated", session_id, payload)
            msg["payload"] = {"todos": todos}
            send(msg)


        def emit_todo_upsert(session_id, payload):
            \"\"\"单条写入（TaskCreate / TaskUpdate）。V2 家族一条任务一次调用。

            实测两种载荷：
            - TaskCreate 入参 `{subject, description, activeForm}`（无 id）。
            - TaskUpdate 入参 `{taskId, status}`（无正文），只能靠 taskId 定位。

            难点：WorkBuddy / Claude Code V2 的 TaskCreate 返回里**没有结构化的
            任务 id**（只有文本 "Task #1 created successfully: <正文>"），而
            TaskUpdate 用的 taskId（如 "21"）与那个显示编号（"#1"）并不对应，
            无法从响应里直接建立 taskId→正文 映射。

            稳妥做法：TaskCreate 把 subject 依次压入 FIFO 队列；TaskUpdate 首次
            见到某个 taskId 时，从队列里弹出一条正文绑定它。因为 Agent 总是按
            列表顺序推进任务，TaskUpdate 的首次出现顺序 == TaskCreate 顺序，
            于是 21→第1条、22→第2条…… 一一对上。同时兼容 Qoder 那种响应里
            带 `task = {id, subject}` 的结构化宿主（有 resp_id 优先用它）。
            \"\"\"
            tool_input = todo_input(payload)
            if not isinstance(tool_input, dict):
                return
            response = payload.get("tool_response")
            if not isinstance(response, dict):
                response = {}
            task = response.get("task")
            if isinstance(task, dict):
                resp_id = str(task.get("id") or task.get("taskId") or "")
                resp_subject = task.get("subject") or task.get("content") or ""
            else:
                resp_id = ""
                resp_subject = ""
            todo_id = str(tool_input.get("taskId") or tool_input.get("task_id")
                          or tool_input.get("id") or resp_id or "").strip()
            content = (tool_input.get("subject") or tool_input.get("content")
                       or tool_input.get("title") or resp_subject or "")
            content = content.strip() if isinstance(content, str) else ""

            state = _load_todo_state(session_id)
            mapping = state.get("tasks") or {}
            queue = list(state.get("queue") or [])

            if content and not todo_id:
                # TaskCreate 无 id：正文压入 FIFO，等 TaskUpdate 来认领。
                if content not in queue:
                    queue.append(content)
            elif content and todo_id:
                # 有正文也有 id（Qoder 结构化响应）：直接登记。
                mapping[todo_id] = content
            elif not content and todo_id:
                # TaskUpdate 无正文：先从映射查，查不到再从队列认领。
                content = mapping.get(todo_id) or ""
                content = content.strip() if isinstance(content, str) else ""
                if not content and queue:
                    content = queue.pop(0)
                    mapping[todo_id] = content

            state["tasks"] = mapping
            state["queue"] = queue
            _save_todo_state(session_id, state)

            if not content:
                return

            status = tool_input.get("status") or tool_input.get("state")
            if not status:
                status = "completed" if tool_input.get("completed") else "pending"
            msg = base_event("todo_item_updated", session_id, payload)
            msg["payload"] = {"todo": {"id": todo_id, "content": content,
                                       "status": str(status)}}
            send(msg)


        def handle_todo_event(session_id, payload, tool_name):
            \"\"\"PostToolUse 上的 todo 转发入口：按工具名分流到覆盖 / 单条。\"\"\"
            if tool_name in TODO_OVERWRITE_TOOLS:
                emit_todo_overwrite(session_id, payload)
            elif tool_name in TODO_UPSERT_TOOLS:
                emit_todo_upsert(session_id, payload)


        def host_decides(hook_event):
            # PermissionRequest 是我们和宿主抢「谁先弹」的那条通道：平台正等我们
            # 的答复，`ask` = 把它自己的弹窗放出来。PreToolUse 平台不等答复，
            # 只认 allow/deny，那里用 allow 退场（等于不干预）。
            return "ask" if hook_event == "PermissionRequest" else "allow"


        def run_question(session_id, payload, questions, hook_event):
            # 同一个提问会从两条通道各来一次（PermissionRequest 与 PreToolUse），
            # 载荷里的 tool_use_id 不保证两边都有，所以按**问题内容**去重：
            # 先到的那条占位并开卡，后到的安静退出，绝不让同一道题问两遍。
            signature = "q-" + "_".join(q["question"][:40] for q in questions)[:120]
            if not claim(session_id, payload, "question", signature):
                return
            request_id = safe_id(payload.get("tool_use_id")
                                 or payload.get("toolUseId")
                                 or payload.get("call_id")
                                 or payload.get("request_id")
                                 or ("q" + str(int(time.time()))))
            msg = base_event("question_requested", session_id, payload)
            msg["request_id"] = request_id
            msg["payload"] = {"questions": questions, "request_id": request_id,
                              # 哪条通道送来的（PermissionRequest / PreToolUse / …）。
                              # 「岛先出现」能不能成立全看这个：PermissionRequest 上
                              # 平台正等着我们的答复，宿主还没画自己的面板。
                              "channel": hook_event}
            if not send(msg):
                emit(host_decides(hook_event),
                     "BetterFocusIDE is not running; ask in the host dialog.", hook_event)
                return
            # 岛可能早就弹过卡（Notification 预取那条通道），用户也已经答完：
            # 直接把答案回灌，绝不再问第二遍，也不必再等一个超时。
            # 只处理单题——多题卡片是逐步写的，提前取会吃掉一半。
            if len(questions) == 1:
                found, label, index = read_answer(session_id, request_id,
                                                  questions[0]["id"], 0)
                if found and index >= 0:
                    reason = ("The person answered on the BetterFocusIDE island. "
                              "Use these answers and continue." + chr(10)
                              + "  - %s: %s" % (questions[0]["header"], label))
                    emit("deny", reason, hook_event)
                    return
                if found and index == -4:
                    emit(host_decides(hook_event),
                         "The person will answer in the host dialog.", hook_event)
                    return
            since = time.time()
            deadline = since + QUESTION_TIMEOUT
            while time.time() < deadline:
                lines, answered, timed_out = [], 0, False
                for q in questions:
                    found, label, index = read_answer(session_id, request_id, q["id"], since)
                    if found and index == -4:
                        # 让位：宿主自带提问面板且正在前台。静默退出（不打印任何
                        # 决策）是本方言的「无决策」——宿主自己的对话框接手。
                        return
                    if found and index == -1:
                        timed_out = True
                    elif found:
                        answered += 1
                    lines.append("  - %s: %s" % (q["header"], label))
                if timed_out:
                    break
                if answered == len(questions) and questions:
                    reason = ("The person answered on the BetterFocusIDE island. "
                              "Use these answers and continue." + chr(10) + chr(10).join(lines))
                    # deny 会拦掉宿主自己的提问对话框，reason 把答案回灌给 Agent。
                    emit("deny", reason, hook_event)
                    return
                time.sleep(1)
            timeout_msg = base_event("question_timeout", session_id, payload)
            timeout_msg["payload"] = {"question_id": questions[0]["id"] if questions else "q1",
                                      "request_id": request_id}
            send(timeout_msg)
            # 没人回答：交回宿主自己的对话框，而不是 deny。deny 等于替人答了
            # 「拒绝回答」，工具会以失败收场；`ask` 才是「平台你接着问」。
            emit(host_decides(hook_event),
                 "The person left the island question unanswered; ask in the host dialog.",
                 hook_event)


        def run_permission(session_id, payload):
            # Notice only: print NOTHING on stdout so the host keeps its own
            # permission dialog. Observer of last resort — the island-side
            # NoticeController debounces a duplicate banner.
            if not claim(session_id, payload, "permission"):
                return
            tool_name = payload.get("tool_name") or ""
            tool_input = payload.get("tool_input") if isinstance(payload.get("tool_input"), dict) else {}
            request_id = safe_id(payload.get("tool_use_id")
                                 or payload.get("toolUseId")
                                 or payload.get("request_id")
                                 or (tool_name + "-" + str(int(time.time() * 1000))))
            detail = ""
            for key in ("command", "file_path", "path", "url", "query", "pattern"):
                value = tool_input.get(key)
                if isinstance(value, str) and value:
                    detail = value
                    break
            if not detail and tool_input:
                detail = json.dumps(tool_input, ensure_ascii=False)[:400]
            if not detail:
                detail = str(payload.get("message") or "")[:400]
            msg = base_event("permission_notice", session_id, payload)
            msg["payload"] = {"request_id": request_id, "tool_name": tool_name,
                              "tool_input": tool_input,
                              "resources": [detail] if detail else [],
                              "flavor": "permission"}
            send(msg)


        # ------------------------------------------------------------------
        # 诊断探针：仅当 /tmp/bf-probe 标记存在时启用，把收到的事件原始
        # 结构 dump 到 /tmp 下可读文件，用来在真机上定位 WorkBuddy 转录里
